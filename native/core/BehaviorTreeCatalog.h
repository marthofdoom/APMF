// ============================================================================
// THE COMBAT BEHAVIOUR TREE CATALOG -- apmf::cbt
//
// PROVENANCE: derived from disassembly of SkyrimSE.exe 1.6.1170, 1.5.97 and 1.7.104 (our own unpacked
// copies, binaries/README.md), clean room, 2026-10-27. Every value below was read out of those three
// executables (RTTI type descriptors, complete object locators, class hierarchy descriptors, vtables and
// the instructions cited) and nothing else; the Address Library files were used only to name the id of
// an RVA we had already derived. The evidence for each value is Docs/BEHAVIOR-TREE-CATALOG.md (tables
// regenerated by the script recorded there). Original work, MIT like the rest of Harbinger.
//
// What it is: the engine's combat AI runs a behaviour tree per combat controller. A "thread" walks the
// tree; every node that DOES something is an instance of one of the CombatBehaviorTreeNodeObject
// class templates (NodeObject<X> for a parameterless node, NodeObject1/2/3<X, params...> for one that
// carries 1-3 constructor parameters). This header lists every one of those classes the three
// executables contain -- 95, the same set on all three -- by vtable, plus the few thread / controller /
// group fields the hooks read. The vtables are hooked by ActionGate (act / pop / update), named by
// CastObserve, CombatApproach and CombatSubstrate. Composite nodes that are not NodeObject* (create-
// context, conditional, value and function nodes) are deliberately not listed: they route, they do not act.
//
// THE NODE PROTOCOL (the thread runner: AE id 47483 0x85DBA0, SE id 46228 0x7C6800, 1.7.104 0x872DD0 --
// the same instruction sequence on all three):
//   thread+0x138 is the node the thread is on, thread+0x14C its phase:
//     phase 2 -> the runner sets phase 1, records the frame offset, enters the node on the thread
//                (AE 0x85E990) and calls vtable slot 0x02 (act, the node's Enter) -- unless the result is
//                already 2 (aborted): then it Ascends straight away;
//     phase 1 -> unless a wait bit (thread+0x150 & 3) is set, slot 0x04 (update), or slot 0x05 when the
//                result word (thread+0x148) is 2 (aborted);
//     phase 0 -> the node above has been returned to: the runner sets phase 1 and calls slot 0x03 (pop,
//                the frame release) on the node that just finished.
//   A node finishes through two engine helpers, both plain field writes:
//     SetFailed(thread, bool) -- AE id 47496 0x85E0A0 / SE 46240 0x7C6D30 / 1.7.104 0x8732D0:
//                                result (+0x148) = the bool, only while the result is <= 1 (2 is sticky);
//     Ascend(thread)          -- AE id 47484 0x85DD70 / SE 46229 0x7C69D0 / 1.7.104 0x872FA0:
//                                node (+0x138) = node->parent (node+0x10), phase (+0x14C) = 0.
//   So "SetFailed(thread, true); Ascend(thread)" is a node's own failure exit, and the runner then pops it.
//   act() and pop() are a PAIR over the thread's DATA STACK (thread+0x00 base, +0x08 capacity, +0x0C top;
//   the runner records the top as the node's frame offset at +0x120 before act): act pushes the node's
//   per-thread state through the push helper (AE id 33171 0x5572A0 -- the PUSH, not SetFailed; the size is
//   rounded up to 4: `lea esi,[r8+3]; and esi,-4`) and pop releases exactly that. ForceFail is the smallest
//   pair: act (AE 0x8B9D90 / SE 0x8218A0 / 1.7.104 0x8CF370) pushes 1 byte (4 after rounding), calls
//   SetFailed(current thread, 1), then tail-jumps to Ascend -- the thread it fails is the current one from
//   thread-local storage (TLS slot +0x6A0), never `this`; pop (AE 0x8B9E50 / SE 0x821950 / 1.7.104 0x8CF430)
//   is `add dword [rdx+0xC], -4; ret`.
//   The runner's thread argument (`control`) and that TLS thread are the same object: the stepping loop
//   (AE id 47363 0x858B10) stores its thread into the TLS slot (0x858B56 `mov [rsi],rdx`, rsi = TLS + 0x6A0)
//   and then calls the runner with that same thread (0x858B60 `mov rcx,rbx`, rbx = rdx).
//   thread+0x158 is the tree's owner (the behaviour controller): a finished child thread wakes its parent
//   thread through it (AE 0x85DD2B), and every leaf reaches its CombatController through owner+0x20 (AE EquipSpell
//   Enter 0x87829F, AE SearchCenter Enter 0x8B2A07, SE 0x81BCE7, 1.7.104 0x8C7F97).
// ============================================================================

