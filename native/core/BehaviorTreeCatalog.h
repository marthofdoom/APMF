    inline constexpr REL::VariantID RTTI_CombatBehaviorTreeNode(686393, 394204, 0);

    // ---- the catalog ----
    // VariantID(SE id, AE id, VR offset). 1.7.104 resolves the AE id through the fork's MIT id table; every
    // row's table entry was checked to be that class's own vtable in the 1.7.104 image. No VR executable was
    // available to derive from, so the VR offset is 0 (and every consumer refuses VR).
    // Names: kLeaves / kSearchLeaves use the node class's own name ("CombatBehavior" + X; a selector template
    // is "CombatBehavior<Selector>_<its argument>"). kParamLeaves name the class plus its parameters, except
    // the two AcquireResource instantiations, named by arity (NodeObject2 = "<2>", NodeObject3 = "<3>"),
    // which is the spelling channels/SubstrateEquip.cpp keys on. Each list is sorted by name.
    struct NodeVtable
    {
        const char*    name;
        REL::VariantID vtbl;
    };

